# --- Protocol constants (docs/evaluation-protocol.md) -----------------------
SEED = 20260811
HORIZON = 7
MIN_TRAIN_PERIODS = 42
FINAL_TEST_PERIODS = 14
SERVICE_LEVEL_TARGET = 0.90
LEAD_TIME_DAYS = 3
REVIEW_PERIOD_DAYS = 1
HOLDING_COST_PER_UNIT_PER_DAY = 0.10
STOCKOUT_COST_PER_UNIT = 2.00
ORDERING_COST_PER_ORDER = 5.00
SENSITIVITY_SCALES = (0.9, 1.0, 1.1)

SYNTHETIC_NOTICE = "Synthetic fixture — not a real business result"

ASSUMPTIONS = (
    "Demand is exogenous to the policy: inventory availability does not change the demand series used in simulation.",
    "Sales lost during a stockout are lost, not backlogged.",
    "Orders placed at the end of a review day arrive at the start of the day lead_time days later; lead time is constant; supply is unlimited.",
    "Holding cost is charged on end-of-day on-hand inventory; ordering cost is charged per order placed; stockout cost is charged per lost unit.",
    "Review happens after demand for the day (end-of-period review).",
    "No perishability/expiry, quantity discounts, or capacity limits.",
    "Forecasts target observed sales; censored demand during stockouts is not recovered.",
    "The fixture is synthetic; no reported number is a real-world result.",
)

LIMITATIONS = (
    "The fixture is a small synthetic series (2 SKUs, ~120 days) styled after the audited source's grain; it is not derived from or representative of FreshRetailNet-50K.",
    "Models use only lags, rolling statistics, and calendar features; discount/holiday/activity/weather covariates are not used.",
    "No per-SKU hyperparameter tuning: fixed documented defaults only.",
    "Policy candidates are generated by documented heuristics; selection is among those candidates and is not an optimality claim.",
    "Demand is observed sales; censoring during stockouts is documented, not corrected.",
)

REPORT_NAME = "experiment_report.json"


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


def _relative_or_abs(path: Path) -> str:
    """Relative to the repo root when nested inside it, else absolute."""
    try:
        return str(path.resolve().relative_to(_repo_root()))
    except ValueError:
        return str(path.resolve())


def _deterministic_timestamp() -> tuple[str, str]:
    raw = os.environ.get("SOURCE_DATE_EPOCH")
    if raw:
        try:
            ts = datetime.fromtimestamp(int(raw), tz=UTC)
            return ts.isoformat(), "SOURCE_DATE_EPOCH"
        except ValueError:
            pass
    return "2026-08-11T00:00:00+00:00", "documented-fixed-value"


def build_models() -> tuple[Forecaster, ...]:
    """The fixed, documented model set. Fresh instances each time."""
    return (
        NaiveForecaster(),
        MovingAverageForecaster(window=7),
        SESForecaster(alpha=0.3),
        HistGradientBoostingForecaster(),
    )


def model_for_id(model_id: str) -> Forecaster:
    for model in build_models():
        if model.model_id == model_id:
            return model
    raise ValueError(f"unknown model_id: {model_id}")


def _demand_values(
    table: DemandTable, sku: str, dates: Sequence[date]
) -> tuple[float, ...]:
    wanted = set(dates)
    values = [r.demand_units for r in table.series_for(sku) if r.date in wanted]
    if len(values) != len(dates):
        raise ValueError(f"sku {sku}: missing demand for requested dates")
    return tuple(values)


def _deployment_forecast(
    table: DemandTable, sku: str, model: Forecaster, horizon: int
) -> tuple[tuple[date, ...], tuple[float, ...], str, str]:
    """Refit `model` on all history and predict the next `horizon` days."""
    fitted = model.fit(table.filter_dates(sku, [r.date for r in table.series_for(sku)]))
    last_date = table.series_for(sku)[-1].date
    start = last_date + timedelta(days=1)
    context = FutureContext(tuple(start + timedelta(days=i) for i in range(horizon)))
    forecast = fitted.predict(context, horizon)
    return forecast.dates, forecast.values, forecast.model_id, forecast.model_version


def _simulation_config(
    table: DemandTable, sku: str, stats: DemandStats
) -> SimulationConfig:
    return SimulationConfig(
        sku=sku,
        initial_inventory=round(
            stats.mean_daily * (LEAD_TIME_DAYS + REVIEW_PERIOD_DAYS), 2
        ),
        lead_time_days=LEAD_TIME_DAYS,
        review_period_days=REVIEW_PERIOD_DAYS,
        holding_cost_per_unit_per_day=HOLDING_COST_PER_UNIT_PER_DAY,
        stockout_cost_per_unit=STOCKOUT_COST_PER_UNIT,
        ordering_cost_per_order=ORDERING_COST_PER_ORDER,
    )


def _manifest_summary(
    manifest: DatasetManifest, fixture_path: Path
) -> dict[str, object]:
    return {
        "name": manifest.name,
        "source_url": manifest.source_url,
        "publisher": manifest.publisher,
        "retrieval_date": manifest.retrieval_date,
        "dataset_version": manifest.dataset_version,
        "license_name": manifest.license_name,
        "license_url": manifest.license_url,
        "fields": list(manifest.fields),
        "checksum_algorithm": manifest.checksum_algorithm,
        "checksum": manifest.checksum,
        "file_path": _relative_or_abs(fixture_path),
        "accepted": manifest.accepted,
        "source_label": "synthetic-fixture",
        "synthetic_notice": SYNTHETIC_NOTICE,
    }


def _build_sku_section(
    *,
    table: DemandTable,
    sku: str,
    splits: TimeSplits,
    models: Sequence[Forecaster],
    manifest: DatasetManifest,
    fixture_path: Path,
    generated_at: str,
    timestamp_source: str,
) -> dict[str, object]:
    stats = _sku_stats(table, sku)
    category = table.category_for(sku)

    backtest = run_backtest(table, models, splits.folds, horizon=HORIZON)
    sku_folds = tuple(ff for ff in backtest.folds if ff.sku == sku)
    sku_summaries = _summaries_for(sku_folds)
    selected = select_best_model(sku_summaries)

    final_test = evaluate_final_test(
        table, sku, model_for_id(selected.model_id), splits
    )

    deployment_dates, deployment_values, dep_model_id, dep_model_version = (
        _deployment_forecast(table, sku, model_for_id(selected.model_id), HORIZON)
    )

    config = _simulation_config(table, sku, stats)
    last_fold = splits.folds[-1]
    selection_dates = last_fold.validation_dates
    selection_demand = _demand_values(table, sku, selection_dates)
    policies = generate_candidates(
        stats, lead_time_days=LEAD_TIME_DAYS, review_period_days=REVIEW_PERIOD_DAYS
    )
    selection_source = DemandSource(kind="observed", reference="last_validation_fold")
    candidates = simulate_candidates(
        policies,
        sku=sku,
        dates=selection_dates,
        demand=selection_demand,
        config=config,
        seed=SEED,
        demand_source=selection_source,
    )
    selection = select_policy(candidates, SERVICE_LEVEL_TARGET)

    evidence = EvidenceBundle(
        dataset_manifest=_manifest_summary(manifest, fixture_path),
        source_label="synthetic-fixture",
        forecast_models=tuple(
            {"model_id": m.model_id, "model_version": m.model_version} for m in models
        ),
        selected_model_id=selected.model_id,
        selected_model_version=selected.model_version,
        backtest_report_path=REPORT_NAME,
        final_test_report_path=REPORT_NAME,
        selection_run_ids={c.policy_id: c.run_id for c in candidates},
        recommendation_run_id="",  # filled by build_recommendation
        sensitivity_run_ids={},
        package_version=PACKAGE_VERSION,
        schema_version=SCHEMA_VERSION,
        protocol_version=PROTOCOL_VERSION,
    )

    recommendation = build_recommendation(
        sku=sku,
        category=category,
        stats=stats,
        selection_candidates=candidates,
        selection_result=selection,
        forecast_model_id=dep_model_id,
        forecast_model_version=dep_model_version,
        forecast_horizon=HORIZON,
        deployment_forecast_dates=deployment_dates,
        deployment_forecast=deployment_values,
        config=config,
        seed=SEED,
        service_level_target=SERVICE_LEVEL_TARGET,
        evidence=evidence,
        assumptions=ASSUMPTIONS,
        limitations=LIMITATIONS,
        generated_at=generated_at,
    )

    return {
        "category": category,
        "stats": stats.to_dict(),
        "backtest": {
            "models": [s.to_dict() for s in sku_summaries],
            "per_fold": [_fold_metric_row(ff) for ff in sku_folds],
            "by_category": {
                g: [s.to_dict() for s in ssum]
                for g, ssum in _grouped(sku_folds, "category").items()
            },
            "by_horizon": {
                g: [s.to_dict() for s in ssum]
                for g, ssum in _grouped(sku_folds, "horizon").items()
            },
        },
        "selection": {
            "rule": "per-SKU: min pooled validation MAE; tie-break lower WMAPE; tie-break lexicographic model_id",
            "selected_model_id": selected.model_id,
            "selected_model_version": selected.model_version,
        },
        "final_test": _final_test_dict(final_test),
        "deployment_forecast": {
            "model_id": dep_model_id,
            "model_version": dep_model_version,
            "horizon": HORIZON,
            "dates": [d.isoformat() for d in deployment_dates],
            "values": [round6(v) for v in deployment_values],
        },
        "policy_selection": selection.to_dict(),
        "recommendation": recommendation.to_dict(),
    }


def _sku_stats(table: DemandTable, sku: str) -> DemandStats:
    values = [value for _, value in table.daily_series(sku)]
    n = len(values)
    mean = sum(values) / n
    variance = sum((v - mean) ** 2 for v in values) / n
    return DemandStats(mean_daily=mean, std_daily=variance**0.5, n_days=n)


def _summaries_for(fold_forecasts: Sequence) -> tuple:
    from .backtesting import summarize

    return summarize(fold_forecasts)


def _grouped(fold_forecasts: Sequence, key: str) -> dict:
    from .backtesting import grouped_summaries

    return grouped_summaries(fold_forecasts, key)


def _fold_metric_row(ff) -> dict[str, object]:
    return {
        "fold_index": ff.fold_index,
        "model_id": ff.model_id,
        "model_version": ff.model_version,
        "metrics": {k: round6(v) for k, v in ff.metrics.items()},
        "insufficient_history": ff.insufficient_history,
        "fallback_reason": ff.fallback_reason,
    }


def _final_test_dict(result: FinalTestResult) -> dict[str, object]:
    return {
        "sku": result.sku,
        "category": result.category,
        "model_id": result.model_id,
        "model_version": result.model_version,
        "dates": [d.isoformat() for d in result.dates],
        "actual": [round6(v) for v in result.actual],
        "predicted": [round6(v) for v in result.predicted],
        "metrics": {k: round6(v) for k, v in result.metrics.items()},
    }


def materialize(
    *,
    fixture_path: Path,
    manifest_path: Path,
    outdir: Path,
) -> Path:
    """Run the full deterministic pipeline; returns the report path."""
    manifest = load_manifest(manifest_path)
    if not manifest.verify_checksum(fixture_path):
        raise RuntimeError(
            f"checksum mismatch for {fixture_path}: manifest declares "
            f"{manifest.checksum}, file is {sha256_file(fixture_path)}"
        )
    table = load_canonical_csv(fixture_path)

    calendar = tuple(sorted({r.date for r in table.records}))
    splits = expanding_origins(
        calendar,
        min_train_periods=MIN_TRAIN_PERIODS,
        horizon=HORIZON,
        final_test_periods=FINAL_TEST_PERIODS,
    )

    models = build_models()
    generated_at, timestamp_source = _deterministic_timestamp()

    per_sku: dict[str, dict[str, object]] = {}
    for sku in table.skus:
        per_sku[sku] = _build_sku_section(
            table=table,
            sku=sku,
            splits=splits,
            models=models,
            manifest=manifest,
            fixture_path=fixture_path,
            generated_at=generated_at,
            timestamp_source=timestamp_source,
        )

    report = ExperimentReport(
        meta={
            "report_version": "1.0",
            "package_version": PACKAGE_VERSION,
            "schema_version": SCHEMA_VERSION,
            "protocol_version": PROTOCOL_VERSION,
            "generated_at": generated_at,
            "timestamp_source": timestamp_source,
            "seed": SEED,
            "report_path": REPORT_NAME,
        },
        dataset=_manifest_summary(manifest, fixture_path),
        protocol={
            "frequency": "daily",
            "horizon": HORIZON,
            "min_train_periods": MIN_TRAIN_PERIODS,
            "final_test_periods": FINAL_TEST_PERIODS,
            "split_policy": "expanding-window rolling origins; step = horizon; final test untouched",
            "service_level_target": SERVICE_LEVEL_TARGET,
            "cost_parameters": {
                "lead_time_days": LEAD_TIME_DAYS,
                "review_period_days": REVIEW_PERIOD_DAYS,
                "holding_cost_per_unit_per_day": HOLDING_COST_PER_UNIT_PER_DAY,
                "stockout_cost_per_unit": STOCKOUT_COST_PER_UNIT,
                "ordering_cost_per_order": ORDERING_COST_PER_ORDER,
            },
            "metrics": "MAE/RMSE/WMAPE/MASE; undefined values are None (see docs/evaluation-protocol.md)",
            "model_selection_rule": "per-SKU min pooled validation MAE; tie-break WMAPE; tie-break model_id; final test excluded",
            "policy_selection_rule": "min total cost subject to service level >= target; infeasible -> highest-service fallback; deterministic tie-breaks",
            "sensitivity_scales": list(SENSITIVITY_SCALES),
            "future_feature_leakage": "none: models use only past lags/rolling stats and calendar features",
        },
        assumptions=ASSUMPTIONS,
        limitations=LIMITATIONS,
        overall={
            "skus": list(table.skus),
            "categories": list(table.categories),
            "num_folds": len(splits.folds),
            "models": [
                {
                    "model_id": m.model_id,
                    "model_version": m.model_version,
                    "min_history": m.min_history,
                }
                for m in models
            ],
            "calendar_start": calendar[0].isoformat(),
            "calendar_end": calendar[-1].isoformat(),
            "final_test_start": splits.final_test_dates[0].isoformat(),
            "final_test_end": splits.final_test_dates[-1].isoformat(),
        },
        per_sku=per_sku,
    )

    outdir.mkdir(parents=True, exist_ok=True)
    report_path = outdir / REPORT_NAME
    report.save(report_path)
    return report_path


def main(argv: Sequence[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(
        description="Deterministic offline evaluation (synthetic fixture only)."
    )
    parser.add_argument(
        "--outdir",
        type=Path,
        default=_repo_root() / "data" / "evaluations",
        help="output directory for the experiment report",
    )
    args = parser.parse_args(argv)

    root = _repo_root()
    fixture = root / "data" / "fixtures" / "freshretailnet_style_synthetic.csv"
    manifest = root / "data" / "manifests" / "fixture_synthetic.json"
    if not fixture.exists():
        print(f"error: fixture not found: {fixture}", file=sys.stderr)
        return 2
    if not manifest.exists():
        print(f"error: manifest not found: {manifest}", file=sys.stderr)
        return 2

    try:
        report_path = materialize(
            fixture_path=fixture, manifest_path=manifest, outdir=args.outdir
        )
    except Exception as exc:  # noqa: BLE001 - CLI boundary
        print(f"error: {exc}", file=sys.stderr)
        return 1

    print(f"wrote {report_path}")
    print(SYNTHETIC_NOTICE)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
