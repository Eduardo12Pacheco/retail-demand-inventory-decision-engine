def main(argv: Sequence[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(
        description="Deterministic offline evaluation over the synthetic fixture or the pinned real snapshot."
    )
    parser.add_argument(
        "--source",
        choices=("fixture", "real"),
        default="fixture",
        help="fixture (offline synthetic, default) or real (pinned snapshot in data/raw)",
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=None,
        help="manifest path (defaults per source mode)",
    )
    parser.add_argument(
        "--population",
        type=Path,
        default=None,
        help="v2 population manifest path for --source real (opt-in; writes the expanded report)",
    )
    parser.add_argument(
        "--raw-dir",
        type=Path,
        default=None,
        help="raw snapshot directory for --source real (default data/raw)",
    )
    parser.add_argument(
        "--outdir",
        type=Path,
        default=None,
        help="output directory for the experiment report",
    )
    args = parser.parse_args(argv)

    root = _repo_root()
    if args.source == "fixture":
        fixture = root / "data" / "fixtures" / "freshretailnet_style_synthetic.csv"
        manifest = (
            args.manifest or root / "data" / "manifests" / "fixture_synthetic.json"
        )
        outdir = args.outdir or root / "data" / "evaluations"
        if not fixture.exists():
            print(f"error: fixture not found: {fixture}", file=sys.stderr)
            return 2
        if not manifest.exists():
            print(f"error: manifest not found: {manifest}", file=sys.stderr)
            return 2
        try:
            report_path = materialize(
                fixture_path=fixture, manifest_path=manifest, outdir=outdir
            )
        except Exception as exc:  # noqa: BLE001 - CLI boundary
            print(f"error: {exc}", file=sys.stderr)
            return 1
        print(f"wrote {report_path}")
        print(SYNTHETIC_NOTICE)
        return 0

    manifest = args.manifest or root / "data" / "manifests" / "freshretailnet-real.json"
    raw_dir = args.raw_dir or root / "data" / "raw"
    outdir = args.outdir or root / "data" / "evaluations"
    if not manifest.exists():
        print(f"error: real manifest not found: {manifest}", file=sys.stderr)
        return 2
    if not raw_dir.exists():
        print(
            f"error: raw snapshot directory not found: {raw_dir}\n"
            "Acquire it first:\n"
            "  uv run python -m retail_demand_inventory.data.acquisition "
            "--manifest data/manifests/freshretailnet-real.json --output-dir data/raw",
            file=sys.stderr,
        )
        return 2
    try:
        if args.population is not None:
            if not args.population.exists():
                print(
                    f"error: population manifest not found: {args.population}",
                    file=sys.stderr,
                )
                return 2
            report_path = materialize_real_expanded(
                manifest_path=manifest,
                population_path=args.population,
                raw_dir=raw_dir,
                outdir=outdir,
            )
        else:
            report_path = materialize_real(
                manifest_path=manifest, raw_dir=raw_dir, outdir=outdir
            )
    except Exception as exc:  # noqa: BLE001 - CLI boundary
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(f"wrote {report_path}")
    print(REAL_LABEL)
    print("NOT a full-dataset result; does not generalize.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
