def _repo_commit() -> tuple[str | None, str]:
    import subprocess

    try:
        out = subprocess.run(
            ["git", "-C", str(_repo_root()), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )
        if out.returncode == 0 and out.stdout.strip():
            return (
                out.stdout.strip(),
                "git HEAD at generation time (report generated before commit; not the eventual commit SHA)",
            )
    except (OSError, subprocess.SubprocessError):
        pass
    return None, "unavailable"


